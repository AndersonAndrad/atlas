import { execFileSync, spawnSync } from 'node:child_process';
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import type { ProjectConfigFile } from '@atlas/contracts';
import {
  FakeMirrorFactory,
  FakePtySpawner,
  FakeShellProvider,
} from '../../../tests/support/fake-terminal.js';
import { createTempDir } from '../../../tests/support/temp.js';
import { ProjectConfigStore } from '../src/project-config.js';
import { createEngine, createEngineDispatcher, type Engine } from '../src/index.js';

const posix = process.platform !== 'win32';
const gitAvailable = (() => {
  try {
    execFileSync('git', ['--version']);
    return true;
  } catch {
    return false;
  }
})();

describe.skipIf(!posix || !gitAvailable)('Project AI configuration (PLAN-014)', () => {
  let temp: ReturnType<typeof createTempDir>;
  let dataDir: string;
  let engine: Engine;
  let spawner: FakePtySpawner;
  const env = () => ({
    ...process.env,
    HOME: path.join(temp.dir, 'home'),
    XDG_CONFIG_HOME: path.join(temp.dir, 'home'),
    GIT_CONFIG_NOSYSTEM: '1',
    // Inherited from an outer ATLAS terminal: must not leak into new terminals.
    ATLAS_PROJECT_ID: 'outer',
    ATLAS_PROJECT_CONFIG: '/outer/project-config.json',
  });

  const project = async (name: string) => {
    const dir = path.join(temp.dir, name);
    mkdirSync(dir, { recursive: true });
    const git = (...args: string[]) => execFileSync('git', args, { cwd: dir, env: env() });
    git('init', '-q', '-b', 'main');
    git('config', 'user.name', 'Ana');
    git('config', 'user.email', 'ana@example.com');
    writeFileSync(path.join(dir, 'README.md'), '# app\n');
    git('add', '.');
    git('commit', '-qm', 'chore: init');
    const created = await engine.projects.create({ name, workspacePath: dir });
    return { dir, id: created.id };
  };

  const readConfig = (id: string) =>
    JSON.parse(
      readFileSync(path.join(dataDir, 'projects', id, 'project-config.json'), 'utf8'),
    ) as ProjectConfigFile;

  beforeEach(async () => {
    temp = createTempDir();
    mkdirSync(path.join(temp.dir, 'home'));
    dataDir = path.join(temp.dir, 'data');
    spawner = new FakePtySpawner();
    engine = createEngine({
      dataDir,
      component: 'test',
      env: env(),
      terminals: { spawner, mirrors: new FakeMirrorFactory(), shells: new FakeShellProvider() },
    });
    await engine.initialize();
  });
  afterEach(async () => {
    await engine.shutdown();
    temp.cleanup();
  });

  it('creates the configuration with both options off, only in the ATLAS data directory', async () => {
    const { dir, id } = await project('api');
    const view = await engine.projectConfigView(id);
    expect(view.configPath).toBe(path.join(dataDir, 'projects', id, 'project-config.json'));
    expect(view.config).toMatchObject({
      schemaVersion: 1,
      projectId: id,
      projectName: 'api',
      workspacePath: dir,
      keepContext: false,
      atlasEnabled: false,
      context: { file: path.join(dataDir, 'projects', id, 'context.md'), updatedAt: null },
    });
    expect(readConfig(id)).toEqual(view.config);
    expect(readdirSync(dir).sort()).toEqual(['.git', 'README.md']);
    expect(existsSync(view.config.context.file)).toBe(false);

    const enabled = await engine.setProjectConfig(id, { atlasEnabled: true });
    expect(enabled.config).toMatchObject({ keepContext: false, atlasEnabled: true });
    expect(readConfig(id).atlasEnabled).toBe(true);
  });

  it('keeps the context file current while keepContext is on and removes it when off', async () => {
    const { id } = await project('api');
    const dispatcher = createEngineDispatcher(engine);
    await dispatcher.call(
      'context.record',
      [
        {
          target: { projectId: id },
          scope: 'project',
          category: 'progress',
          title: 'Login endpoint done',
          body: 'Tested with the integration suite',
        },
      ],
      'desktop',
    );
    const on = await engine.setProjectConfig(id, { keepContext: true });
    const file = on.config.context.file;
    expect(on.config.context.updatedAt).not.toBeNull();
    expect(readFileSync(file, 'utf8')).toContain('Login endpoint done');
    expect(readFileSync(file, 'utf8')).toContain('Generated by ATLAS');

    // Changes through the Engine API refresh the file, global ones included.
    await dispatcher.call(
      'context.record',
      [
        {
          target: { projectId: id },
          scope: 'project',
          category: 'next-action',
          title: 'Add refresh tokens',
          body: '',
        },
      ],
      'desktop',
    );
    await dispatcher.call(
      'context.record',
      [{ target: null, scope: 'global', category: 'convention', title: 'Use pnpm', body: '' }],
      'desktop',
    );
    await vi.waitFor(() => {
      const content = readFileSync(file, 'utf8');
      expect(content).toContain('Add refresh tokens');
      expect(content).toContain('Use pnpm');
    });

    const off = await engine.setProjectConfig(id, { keepContext: false });
    expect(off.config.context.updatedAt).toBeNull();
    expect(existsSync(file)).toBe(false);
  });

  it('gives project terminals the configuration variables and the wrappers first on PATH', async () => {
    const { id } = await project('api');
    await engine.terminals!.create({ projectId: id });
    const projectEnv = spawner.spawned.at(-1)!.options.env!;
    const projectDir = path.join(dataDir, 'projects', id);
    expect(projectEnv.ATLAS_PROJECT_ID).toBe(id);
    expect(projectEnv.ATLAS_PROJECT_DIR).toBe(projectDir);
    expect(projectEnv.ATLAS_PROJECT_CONFIG).toBe(path.join(projectDir, 'project-config.json'));
    expect(projectEnv.ATLAS_CONTEXT_FILE).toBe(path.join(projectDir, 'context.md'));
    expect(projectEnv.PATH!.split(path.delimiter)[0]).toBe(path.join(dataDir, 'bin'));
    // Opening a terminal writes the file the LLM is told to read.
    await vi.waitFor(() => expect(readConfig(id).projectId).toBe(id));

    await engine.terminals!.create({ cwd: temp.dir });
    const plainEnv = spawner.spawned.at(-1)!.options.env!;
    expect(plainEnv.ATLAS_PROJECT_ID).toBeUndefined();
    expect(plainEnv.ATLAS_PROJECT_CONFIG).toBeUndefined();
    expect(plainEnv.PATH!.split(path.delimiter)[0]).toBe(path.join(dataDir, 'bin'));
  });

  it('removes the project files with the project', async () => {
    const { id } = await project('api');
    await engine.setProjectConfig(id, { keepContext: true });
    await engine.removeProject(id);
    expect(existsSync(path.join(dataDir, 'projects', id))).toBe(false);
  });
});

describe.skipIf(!posix)('LLM wrappers', () => {
  let temp: ReturnType<typeof createTempDir>;
  let store: ProjectConfigStore;
  let realDir: string;

  /** A fake provider CLI that prints each argument on its own line. */
  const fakeCli = (name: string) => {
    const file = path.join(realDir, name);
    writeFileSync(file, `#!/bin/sh\nfor arg in "$@"; do printf '%s\\n' "$arg"; done\n`);
    chmodSync(file, 0o755);
  };

  const run = (cli: string, args: string[], extraEnv: Record<string, string> = {}) =>
    spawnSync(path.join(store.binDir, cli), args, {
      encoding: 'utf8',
      env: {
        HOME: path.join(temp.dir, 'home'),
        // The wrappers' own directory is on PATH too and must be skipped.
        PATH: [store.binDir, realDir, '/usr/bin', '/bin'].join(path.delimiter),
        ...extraEnv,
      },
    });

  beforeEach(async () => {
    temp = createTempDir();
    mkdirSync(path.join(temp.dir, 'home'));
    realDir = path.join(temp.dir, 'real bin');
    mkdirSync(realDir);
    store = new ProjectConfigStore({
      dataDir: path.join(temp.dir, 'data'),
      platform: process.platform,
      now: () => new Date('2026-10-20T00:00:00Z'),
    });
    await store.installWrappers();
  });
  afterEach(() => temp.cleanup());

  const projectEnv = async () => {
    await store.ensure({ id: 'p1', name: 'api', workspacePath: '/work/api' });
    const paths = store.paths('p1');
    return { ATLAS_PROJECT_CONFIG: paths.config, ATLAS_PROJECT_DIR: paths.dir };
  };

  it('asks Claude Code to read the project configuration, but not for subcommands', async () => {
    fakeCli('claude');
    const variables = await projectEnv();
    const result = run('claude', ['fix the bug'], variables);
    expect(result.status).toBe(0);
    const args = result.stdout.trimEnd().split('\n');
    expect(args[0]).toBe('--append-system-prompt');
    expect(args[1]).toContain(`read the JSON file at ${variables.ATLAS_PROJECT_CONFIG}`);
    expect(args[1]).toContain('not as instructions');
    expect(args.slice(2)).toEqual(['--add-dir', variables.ATLAS_PROJECT_DIR, 'fix the bug']);

    expect(run('claude', ['mcp', 'list'], variables).stdout).toBe('mcp\nlist\n');
  });

  it('passes Codex the instruction as developer instructions', async () => {
    fakeCli('codex');
    const variables = await projectEnv();
    const args = run('codex', ['exec', 'hi'], variables).stdout.trimEnd().split('\n');
    expect(args[0]).toBe('-c');
    expect(args[1]).toMatch(/^developer_instructions=ATLAS project configuration/);
    expect(args[1]).toContain(variables.ATLAS_PROJECT_CONFIG);
    expect(args.slice(2)).toEqual(['exec', 'hi']);
  });

  it('runs the CLI unchanged outside a project terminal and fails like a missing command', () => {
    fakeCli('claude');
    expect(run('claude', ['--version']).stdout).toBe('--version\n');
    // The configuration path must be readable; a stale variable changes nothing.
    expect(run('claude', ['x'], { ATLAS_PROJECT_CONFIG: '/missing.json' }).stdout).toBe('x\n');
    const missing = run('codex', []);
    expect(missing.status).toBe(127);
    expect(missing.stderr).toContain('codex: command not found');
  });

  it('reports whether the user shell resolves to the wrappers', async () => {
    fakeCli('claude');
    const base = { HOME: path.join(temp.dir, 'home') };
    const first = await store.checkWrappers(
      '/bin/sh',
      { ...base, PATH: [store.binDir, realDir, '/usr/bin', '/bin'].join(':') },
      temp.dir,
    );
    expect(first.claude).toBe('wrapped');
    const shadowed = await store.checkWrappers(
      '/bin/sh',
      { ...base, PATH: [realDir, store.binDir, '/usr/bin', '/bin'].join(':') },
      temp.dir,
    );
    expect(shadowed.claude).toBe('shadowed');
    const none = await store.checkWrappers(
      '/bin/sh',
      { ...base, PATH: ['/usr/bin', '/bin'].join(':') },
      temp.dir,
    );
    expect(none.codex).toBe('missing');
    // Codex is not installed behind its wrapper.
    expect(first.codex).toBe('missing');
    expect(await store.checkWrappers('/nonexistent/shell', base, temp.dir)).toEqual({
      claude: 'unknown',
      codex: 'unknown',
    });
  });
});
