import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import type { ProjectConfigFile } from '@atlas/contracts';
import {
  FakeMirrorFactory,
  FakePtySpawner,
  FakeShellProvider,
} from '../../../tests/support/fake-terminal.js';
